"""Builds intro/kd-intro.js from kd-intro.src.js and the real logo artwork.
   python3 intro/build_intro.py"""
import pathlib
import re

HERE = pathlib.Path(__file__).parent
svg = (HERE.parent / "src/assets/img/logo-light-text.svg").read_text()
d = [m[0] for m in re.findall(r'<path d="([^"]+)" fill="([^"]+)"/>', svg)]
assert len(d) == 15, len(d)
# order in the file: 0 amber, 1 orange, 2 green, 3 red, 4 orange sliver, 5 needle, 6 K, 7 P, 8 I, 9-14 DRIVER
seg = [("seg seg-a", d[0], "#FCAF17"), ("seg seg-o", d[1], "#EA8C1C"), ("seg seg-g", d[2], "#45B649"),
       ("seg seg-r", d[3], "#ED2024"), ("seg seg-o", d[4], "#EA8C1C")]
logo = (
    '<svg class="kdi__logo" viewBox="0 0 1394 770" fill="none" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">'
    '<defs><filter id="kdglow" x="-40%" y="-40%" width="180%" height="180%"><feGaussianBlur stdDeviation="16"/></filter>'
    '<clipPath id="kddrv"><rect x="0" y="505" width="1394" height="225"/></clipPath></defs>'
    '<g class="glowcopy" filter="url(#kdglow)" opacity="0">' + "".join(f'<path d="{p}" fill="{c}"/>' for _, p, c in seg) + "</g>"
    '<g class="gauge">' + "".join(f'<path class="{k}" d="{p}" fill="{c}"/>' for k, p, c in seg) + "</g>"
    f'<path class="needle" d="{d[5]}" fill="#FDFDFD"/>'
    '<g class="kpi">' + "".join(f'<path d="{p}" fill="#FDFDFD"/>' for p in d[6:9]) + "</g>"
    '<g class="driver" clip-path="url(#kddrv)">' + "".join(f'<path d="{p}" fill="#377DC0"/>' for p in d[9:15]) + "</g>"
    "</svg>"
)
assert "'" not in logo and "\n" not in logo
src = (HERE / "kd-intro.src.js").read_text()
assert src.count("'__LOGO__'") == 1
out = HERE / "kd-intro.js"
out.write_text("/* Generated by intro/build_intro.py — edit kd-intro.src.js instead. */\n" + src.replace("'__LOGO__'", "'" + logo + "'"))
print(out, out.stat().st_size // 1024, "KB")
